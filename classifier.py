def match_keyword(keyword, text):
    """
    Checks if keyword matches text.
    Uses regex word boundaries for single words or short tokens
    to prevent substrings like 'tor' matching 'editor', 'monitor', or 'initiator'.
    """
    kw = keyword.lower().strip()
    if not kw or not text:
        return False
    if " " in kw:
        return kw in text
    pattern = r'(?<![a-zA-Z0-9_а-яА-ЯёЁ])' + re.escape(kw) + r'(?![a-zA-Z0-9_а-яА-ЯёЁ])'
    return bool(re.search(pattern, text, re.IGNORECASE))

def classify_app(name, path="", desc=""):
    clean_name = name.strip()
    clean_name_l = clean_name.lower()
    base_exe = os.path.basename(path).lower() if path else ""
    base_exe_no_ext = os.path.splitext(base_exe)[0] if base_exe else ""

    # 1. Exact direct match in KNOWN_APPS by normalized name
    if clean_name_l in KNOWN_APPS:
        cat = KNOWN_APPS[clean_name_l][0]
        log_classification(name, path, desc, cat, f"KNOWN_APPS exact match for '{clean_name_l}'")
        return cat

    # 2. Match in KNOWN_EXECUTABLES by exact exe name or without extension
    if base_exe and base_exe in KNOWN_EXECUTABLES:
        cat = KNOWN_EXECUTABLES[base_exe][0]
        log_classification(name, path, desc, cat, f"KNOWN_EXECUTABLES exact match for '{base_exe}'")
        return cat
    if base_exe_no_ext and base_exe_no_ext in KNOWN_EXECUTABLES:
        cat = KNOWN_EXECUTABLES[base_exe_no_ext][0]
        log_classification(name, path, desc, cat, f"KNOWN_EXECUTABLES match for '{base_exe_no_ext}'")
        return cat
    if base_exe_no_ext and base_exe_no_ext in KNOWN_APPS:
        cat = KNOWN_APPS[base_exe_no_ext][0]
        log_classification(name, path, desc, cat, f"KNOWN_APPS executable match for '{base_exe_no_ext}'")
        return cat

    # 3. Match in KNOWN_APPS by pattern / prefix (prefer longest matching key)
    best_match = None
    best_len = 0
    for k, (cat, _) in KNOWN_APPS.items():
        if match_keyword(k, clean_name_l) or (len(k) > 4 and k in clean_name_l):
            if len(k) > best_len:
                best_match = (k, cat)
                best_len = len(k)
    if best_match:
        k, cat = best_match
        log_classification(name, path, desc, cat, f"KNOWN_APPS pattern match for '{k}' (len={best_len})")
        return cat

    # 4. Multi-signal heuristic scoring for unknown applications
    # Strongest signal: clean_name (+10), base_exe (+6), PE file desc (+4), directory path (+2)
    path_l = path.lower() if path else ""
    desc_l = desc.lower() if desc else ""
    
    scores = {}
    matched_reasons = {}

    for cat, rules in CATEGORY_RULES.items():
        score = 0
        reasons = []
        for kw in rules["keywords"]:
            if match_keyword(kw, clean_name_l):
                score += 10
                reasons.append(f"{kw} in name (+10)")
            elif base_exe_no_ext and match_keyword(kw, base_exe_no_ext):
                score += 6
                reasons.append(f"{kw} in exe (+6)")
            elif desc_l and match_keyword(kw, desc_l):
                score += 4
                reasons.append(f"{kw} in desc (+4)")
            elif path_l and match_keyword(kw, path_l):
                score += 2
                reasons.append(f"{kw} in path (+2)")
                
        if score > 0:
            scores[cat] = score
            matched_reasons[cat] = ", ".join(reasons)

    # Contextual disambiguation & penalty rules
    # Game Launcher vs Development disambiguation:
    is_game_launcher_term = any(t in clean_name_l or t in base_exe for t in ["launcher", "лаунчер", "overwolf", "nexus", "vortex"])
    is_gaming_path = any(gp in path_l for gp in [r"\epic games\\", r"\steam\\", r"\riot games\\", r"\ubisoft\\", r"\gog galaxy\\", "epic games", "steamapps"])
    
    if is_game_launcher_term and not any(t in clean_name_l for t in ["sdk", "ide", "compiler"]):
        scores["10. Игровой софт и Лаунчеры"] = scores.get("10. Игровой софт и Лаунчеры", 0) + 25
        if "01. Разработка и Код" in scores:
            scores["01. Разработка и Код"] -= 30

    if is_gaming_path and "01. Разработка и Код" in scores:
        scores["01. Разработка и Код"] -= 30

    if any(b in clean_name_l for b in ["browser", "браузер"]):
        scores["04. Интернет и Браузеры"] = scores.get("04. Интернет и Браузеры", 0) + 20

    if any(v in clean_name_l for v in ["vpn", "впн", "proxy", "прокси"]):
        scores["06. Удаленный доступ и Сеть"] = scores.get("06. Удаленный доступ и Сеть", 0) + 20

    # Filter out non-positive scores
    positive_scores = {k: v for k, v in scores.items() if v > 0}

    if positive_scores:
        best_cat = max(positive_scores.items(), key=lambda x: x[1])[0]
        log_classification(name, path, desc, best_cat, f"Heuristic score ({positive_scores[best_cat]} pts): {matched_reasons.get(best_cat, '')}")
        return best_cat

    fallback = "12. Система и Обслуживание"
    log_classification(name, path, desc, fallback, "Fallback default (no rules matched)")
    return fallback

